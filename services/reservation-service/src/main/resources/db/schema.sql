-- reservation-service 배포용 스키마
-- reservation_service 데이터베이스에 연결한 뒤 실행한다.
--   psql -d reservation_service -v ON_ERROR_STOP=1 -f schema.sql
-- 데이터베이스와 기존 행은 지우지 않는다. 없는 테이블과 인덱스만 만든다.
-- LocalDateTime → TIMESTAMP, LocalDate → DATE, LocalTime → TIME
-- building_id, user_id, admin_id 는 다른 서비스 ID만 저장한다. 물리 FK 는 두지 않는다.

-- 공용 자원 (공간 SPACE, 물품 ITEM)
CREATE TABLE IF NOT EXISTS shared_resources (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id      BIGINT,
    resource_name    VARCHAR(100) NOT NULL,
    resource_type    VARCHAR(30)  NOT NULL,
    description      VARCHAR(255),
    resource_status  VARCHAR(30)  NOT NULL DEFAULT 'AVAILABLE',
    max_usage_hours  INTEGER      NOT NULL DEFAULT 2,
    image_url        VARCHAR(500),
    location         VARCHAR(100),
    capacity         INTEGER,
    opening_time     TIME,
    closing_time     TIME,
    created_at       TIMESTAMP    NOT NULL,
    updated_at       TIMESTAMP    NOT NULL,
    CONSTRAINT chk_shared_resources_resource_type
        CHECK (resource_type IN ('ITEM', 'SPACE')),
    CONSTRAINT chk_shared_resources_max_usage_hours
        CHECK (max_usage_hours > 0),
    CONSTRAINT chk_shared_resources_capacity
        CHECK (capacity IS NULL OR capacity > 0),
    CONSTRAINT chk_shared_resources_hours
        CHECK (opening_time IS NULL OR closing_time IS NULL OR opening_time < closing_time)
);

COMMENT ON TABLE shared_resources IS '건물 공용 자원';
COMMENT ON COLUMN shared_resources.building_id IS '매물 서비스 건물 ID. 물리 FK 없음';
COMMENT ON COLUMN shared_resources.resource_type IS 'ITEM 물품, SPACE 공간';
COMMENT ON COLUMN shared_resources.resource_status IS '이용 상태. 예약 가능 값은 AVAILABLE';
COMMENT ON COLUMN shared_resources.max_usage_hours IS '최대 이용 시간. 자동 연장을 더하면 이 값 + 1시간까지';
COMMENT ON COLUMN shared_resources.description IS '엔티티에 length가 없어 VARCHAR(255)';

-- 공용 자원 예약
CREATE TABLE IF NOT EXISTS resource_reservations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_number  VARCHAR(30) NOT NULL,
    resource_id         BIGINT      NOT NULL,
    user_id             BIGINT      NOT NULL,
    reservation_date    DATE        NOT NULL,
    start_time          TIME        NOT NULL,
    end_time            TIME        NOT NULL,
    status              VARCHAR(30) NOT NULL DEFAULT 'REQUESTED',
    returned_at         TIMESTAMP,
    is_overdue          BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMP   NOT NULL,
    updated_at          TIMESTAMP   NOT NULL,
    qr_token            VARCHAR(100),
    checked_in_at       TIMESTAMP,
    CONSTRAINT uq_resource_reservations_reservation_number UNIQUE (reservation_number),
    CONSTRAINT uq_resource_reservations_qr_token UNIQUE (qr_token),
    CONSTRAINT fk_resource_reservations_resource
        FOREIGN KEY (resource_id) REFERENCES shared_resources (id),
    CONSTRAINT chk_resource_reservations_status
        CHECK (status IN ('REQUESTED', 'APPROVED', 'CANCELED', 'COMPLETED', 'EXPIRED', 'OVERDUE')),
    CONSTRAINT chk_resource_reservations_time
        CHECK (end_time > start_time)
);

COMMENT ON TABLE resource_reservations IS '공용 자원 예약';
COMMENT ON COLUMN resource_reservations.user_id IS '유저 서비스 회원 ID. 물리 FK 없음';
COMMENT ON COLUMN resource_reservations.status IS 'REQUESTED, APPROVED, CANCELED, COMPLETED, EXPIRED, OVERDUE';
COMMENT ON COLUMN resource_reservations.returned_at IS '물품 실제 반납 시각';
COMMENT ON COLUMN resource_reservations.is_overdue IS '연체 이력 여부';
COMMENT ON COLUMN resource_reservations.qr_token IS '예약별 QR 토큰. 일반 예약 응답에는 내리지 않음';
COMMENT ON COLUMN resource_reservations.checked_in_at IS 'QR 스캔으로 체크인한 시각';

-- 예약 연장. 엔티티 필드 extensionStatus 의 컬럼명은 status
CREATE TABLE IF NOT EXISTS reservation_extensions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id      BIGINT       NOT NULL,
    requested_end_time  TIME         NOT NULL,
    status              VARCHAR(255) NOT NULL DEFAULT 'REQUESTED',
    extension_type      VARCHAR(255),
    admin_id            BIGINT,
    extension_reason    VARCHAR(500),
    created_at          TIMESTAMP    NOT NULL,
    CONSTRAINT fk_reservation_extensions_reservation
        FOREIGN KEY (reservation_id) REFERENCES resource_reservations (id),
    CONSTRAINT chk_reservation_extensions_status
        CHECK (status IN ('REQUESTED', 'APPROVED')),
    CONSTRAINT chk_reservation_extensions_type
        CHECK (extension_type IS NULL OR extension_type IN ('AUTO', 'EMERGENCY'))
);

COMMENT ON TABLE reservation_extensions IS '예약 연장 기록. AUTO 는 사용자 자동 연장, EMERGENCY 는 관리자 추가 연장';
COMMENT ON COLUMN reservation_extensions.status IS '연장 처리 상태. REQUESTED, APPROVED';
COMMENT ON COLUMN reservation_extensions.admin_id IS '긴급 연장을 처리한 관리자 ID. 물리 FK 없음';
COMMENT ON COLUMN reservation_extensions.extension_reason IS '관리자 긴급 연장 사유';

CREATE INDEX IF NOT EXISTS idx_shared_resources_building_id
    ON shared_resources (building_id);

CREATE INDEX IF NOT EXISTS idx_resource_reservations_resource_date
    ON resource_reservations (resource_id, reservation_date);

CREATE INDEX IF NOT EXISTS idx_resource_reservations_status
    ON resource_reservations (status);

CREATE INDEX IF NOT EXISTS idx_resource_reservations_unreturned
    ON resource_reservations (resource_id)
    WHERE returned_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_reservation_extensions_reservation_status
    ON reservation_extensions (reservation_id, status);

-- 공용 자원 문의. 엔티티 ResourceInquiry
CREATE TABLE IF NOT EXISTS resource_inquiries (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL,
    reservation_id  BIGINT       NOT NULL,
    inquiry_type    VARCHAR(255) NOT NULL,
    content         TEXT         NOT NULL,
    status          VARCHAR(255) NOT NULL DEFAULT 'PENDING',
    created_at      TIMESTAMP    NOT NULL,
    admin_reply     TEXT,
    replied_at      TIMESTAMP,
    CONSTRAINT fk_resource_inquiries_reservation
        FOREIGN KEY (reservation_id) REFERENCES resource_reservations (id),
    CONSTRAINT chk_resource_inquiries_type
        CHECK (inquiry_type IN ('EXTENSION', 'BREAKDOWN', 'OTHER'))
);

COMMENT ON TABLE resource_inquiries IS '공용 자원 예약 문의';
COMMENT ON COLUMN resource_inquiries.user_id IS '문의한 회원 ID. 물리 FK 없음';
COMMENT ON COLUMN resource_inquiries.reservation_id IS '대상 예약 ID';
COMMENT ON COLUMN resource_inquiries.inquiry_type IS 'EXTENSION 추가 연장, BREAKDOWN 고장, OTHER 기타';
COMMENT ON COLUMN resource_inquiries.status IS '문의 상태. 등록 시 PENDING';

CREATE INDEX IF NOT EXISTS idx_resource_inquiries_user_id
    ON resource_inquiries (user_id);

CREATE INDEX IF NOT EXISTS idx_resource_inquiries_reservation_id
    ON resource_inquiries (reservation_id);
