-- property-service DB 초기화 스크립트
DROP DATABASE IF EXISTS property_service;
CREATE DATABASE property_service ENCODING 'UTF8';

\c property_service;

-- 기존 테이블 삭제 (자식 테이블부터)
DROP TABLE IF EXISTS building_contract_forms CASCADE;
DROP TABLE IF EXISTS room_facilities CASCADE;
DROP TABLE IF EXISTS building_facilities CASCADE;
DROP TABLE IF EXISTS rooms CASCADE;
DROP TABLE IF EXISTS buildings CASCADE;

-- buildings 테이블 (건물)
CREATE TABLE buildings (
                           id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                           building_name       VARCHAR(200) NOT NULL,
                           address             VARCHAR(500) NOT NULL,
                           region              VARCHAR(100) NOT NULL,
                           building_type       VARCHAR(50) NOT NULL,
                           total_floors        INTEGER NOT NULL,
                           parking_available   BOOLEAN NOT NULL DEFAULT FALSE,
                           elevator_available  BOOLEAN NOT NULL DEFAULT FALSE,
                           description         TEXT,
                           contact_phone       VARCHAR(30),
                           image_url           VARCHAR(500),
                           is_deleted          BOOLEAN NOT NULL DEFAULT FALSE,
                           created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                           updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                           CONSTRAINT chk_buildings_total_floors CHECK (total_floors > 0)
);

COMMENT ON TABLE buildings IS '건물 정보';
COMMENT ON COLUMN buildings.region IS '지역 검색용 지역명';
COMMENT ON COLUMN buildings.image_url IS '대표 이미지 공개 URL (매물 서비스가 저장한 파일)';
COMMENT ON COLUMN buildings.is_deleted IS '소프트 삭제 여부';

-- rooms 테이블 (호실)
CREATE TABLE rooms (
                       id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       building_id         BIGINT NOT NULL,
                       room_name           VARCHAR(100) NOT NULL,
                       room_type           VARCHAR(50) NOT NULL,
                       room_structure      VARCHAR(100),
                       rental_type         VARCHAR(30) NOT NULL,
                       monthly_fee         BIGINT NOT NULL,
                       deposit             BIGINT NOT NULL DEFAULT 0,
                       management_fee      BIGINT NOT NULL DEFAULT 0,
                       floor_number        INTEGER NOT NULL,
                       area                NUMERIC(10, 2) NOT NULL,
                       capacity            SMALLINT NOT NULL DEFAULT 1,
                       is_deleted          BOOLEAN NOT NULL DEFAULT FALSE,
                       created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                       updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                       CONSTRAINT fk_rooms_building FOREIGN KEY (building_id) REFERENCES buildings (id),
                       CONSTRAINT chk_rooms_monthly_fee CHECK (monthly_fee >= 0),
                       CONSTRAINT chk_rooms_deposit CHECK (deposit >= 0),
                       CONSTRAINT chk_rooms_management_fee CHECK (management_fee >= 0),
                       CONSTRAINT chk_rooms_area CHECK (area > 0),
                       CONSTRAINT chk_rooms_capacity CHECK (capacity > 0),
                       CONSTRAINT chk_rooms_rental_type CHECK (rental_type IN ('MONTHLY', 'SHORT_TERM', 'OTHER'))
);

COMMENT ON TABLE rooms IS '건물별 호실 및 임대 정보';
COMMENT ON COLUMN rooms.monthly_fee IS '월 이용료 또는 월세';
COMMENT ON COLUMN rooms.is_deleted IS '소프트 삭제 여부';

-- building_facilities 테이블 (건물 공용시설)
CREATE TABLE building_facilities (
                                     id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     building_id         BIGINT NOT NULL,
                                     facility_type       VARCHAR(50) NOT NULL,
                                     facility_name       VARCHAR(100) NOT NULL,
                                     created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                                     updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                                     CONSTRAINT fk_building_facilities_building FOREIGN KEY (building_id) REFERENCES buildings (id),
                                     CONSTRAINT uq_building_facility UNIQUE (building_id, facility_type, facility_name)
);

COMMENT ON TABLE building_facilities IS '건물에 속한 공용시설';

-- room_facilities 테이블 (호실 시설)
CREATE TABLE room_facilities (
                                 id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 room_id             BIGINT NOT NULL,
                                 facility_type       VARCHAR(50) NOT NULL,
                                 facility_name       VARCHAR(100) NOT NULL,
                                 created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                                 updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                                 CONSTRAINT fk_room_facilities_room FOREIGN KEY (room_id) REFERENCES rooms (id),
                                 CONSTRAINT uq_room_facility UNIQUE (room_id, facility_type, facility_name)
);

COMMENT ON TABLE room_facilities IS '호실별 시설';

-- building_contract_forms 테이블 (건물·언어별 계약서 양식)
-- form_id 는 문서 서비스(document_forms.id)가 소유하므로 외래 키를 두지 않음
CREATE TABLE building_contract_forms (
                                         id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         building_id         BIGINT NOT NULL,
                                         language            VARCHAR(10) NOT NULL,
                                         form_id             BIGINT NOT NULL,
                                         CONSTRAINT fk_building_contract_forms_building FOREIGN KEY (building_id) REFERENCES buildings (id),
                                         CONSTRAINT uq_building_contract_form UNIQUE (building_id, language),
                                         CONSTRAINT chk_building_contract_forms_language CHECK (language IN ('ko', 'en'))
    );

COMMENT ON TABLE building_contract_forms IS '건물·언어별 계약서 양식 (문서 서비스 양식 ID)';

-- 인덱스
CREATE INDEX idx_buildings_name ON buildings (building_name) WHERE is_deleted = FALSE;
CREATE INDEX idx_buildings_region ON buildings (region) WHERE is_deleted = FALSE;
CREATE INDEX idx_buildings_address ON buildings (address);
CREATE INDEX idx_rooms_building ON rooms (building_id) WHERE is_deleted = FALSE;
CREATE INDEX idx_rooms_monthly_fee ON rooms (monthly_fee) WHERE is_deleted = FALSE;
CREATE INDEX idx_rooms_deposit ON rooms (deposit) WHERE is_deleted = FALSE;
CREATE INDEX idx_rooms_type ON rooms (room_type) WHERE is_deleted = FALSE;
CREATE INDEX idx_building_facilities_building ON building_facilities (building_id);
CREATE INDEX idx_room_facilities_room ON room_facilities (room_id);

