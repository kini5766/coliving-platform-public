-- 로그인 이메일은 user_email_accounts.email 이다.
-- email, name, phone, address, contract_language 는 계약서 자동완성 한 테이블에만 있다.
-- 회원 조회 때 그 행을 읽지 않는다.
DROP TABLE IF EXISTS user_roles CASCADE;
DROP TABLE IF EXISTS user_social_accounts CASCADE;
DROP TABLE IF EXISTS user_email_accounts CASCADE;
DROP TABLE IF EXISTS contract_autocomplete CASCADE;
DROP TABLE IF EXISTS users CASCADE;
DROP TABLE IF EXISTS email_autocomplete CASCADE;
DROP TABLE IF EXISTS name_autocomplete CASCADE;
DROP TABLE IF EXISTS phone_autocomplete CASCADE;
DROP TABLE IF EXISTS address_autocomplete CASCADE;
DROP TABLE IF EXISTS contract_language_autocomplete CASCADE;

CREATE TABLE users (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname             VARCHAR(100),
    enabled              BOOLEAN NOT NULL DEFAULT TRUE,
    account_non_locked   BOOLEAN NOT NULL DEFAULT TRUE,
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP
);

-- 계약서 자동완성. 회원 1명당 1행. users 를 조회할 때 이 행은 읽지 않는다.
-- email, name, phone, address 는 Envelope Encryption 암호문(TEXT)이다.
-- 형식: env1. + Base64(version, kekVersion, wrapIv, wrappedDek, dataIv, ciphertext)
CREATE TABLE contract_autocomplete (
    user_id              BIGINT PRIMARY KEY,
    email                TEXT,
    name                 TEXT,
    phone                TEXT,
    address              TEXT,
    contract_language    VARCHAR(10),
    created_at           TIMESTAMP,
    updated_at           TIMESTAMP,
    CONSTRAINT fk_contract_autocomplete_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

COMMENT ON TABLE contract_autocomplete IS '계약서 자동완성. 이 기능에서만 조회한다.';
COMMENT ON COLUMN contract_autocomplete.email IS 'Envelope Encryption (env1.). KEK로 DEK를 감싸고 DEK로 AES-256-GCM.';
COMMENT ON COLUMN contract_autocomplete.name IS 'Envelope Encryption (env1.). KEK로 DEK를 감싸고 DEK로 AES-256-GCM.';
COMMENT ON COLUMN contract_autocomplete.phone IS 'Envelope Encryption (env1.). KEK로 DEK를 감싸고 DEK로 AES-256-GCM.';
COMMENT ON COLUMN contract_autocomplete.address IS 'Envelope Encryption (env1.). KEK로 DEK를 감싸고 DEK로 AES-256-GCM.';
COMMENT ON COLUMN contract_autocomplete.contract_language IS '계약 언어 코드. 평문.';

-- 계정 역할. 비회원(GUEST)은 로그인하지 않은 방문자라 이 테이블에 넣지 않는다.
-- USER 회원, CANDIDATE 후보자, RESIDENT 입주자, ADMIN 관리자
CREATE TABLE user_roles (
    user_id   BIGINT NOT NULL,
    role      VARCHAR(255) NOT NULL,
    CONSTRAINT user_roles_pkey PRIMARY KEY (user_id, role),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT user_roles_role_check CHECK (role IN ('USER', 'CANDIDATE', 'RESIDENT', 'ADMIN'))
);

-- user_email_accounts 테이블 (이메일 로그인, 사용자당 1행)
CREATE TABLE user_email_accounts (
    user_id      BIGINT PRIMARY KEY,
    email        VARCHAR(255) NOT NULL,
    password     VARCHAR(255) NOT NULL,
    created_at   TIMESTAMP,
    updated_at   TIMESTAMP,
    CONSTRAINT uk_user_email_accounts_email UNIQUE (email),
    CONSTRAINT fk_user_email_accounts_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

-- user_social_accounts 테이블
CREATE TABLE user_social_accounts (
    id              VARCHAR(255) PRIMARY KEY,
    user_id         BIGINT NOT NULL,
    provider_type   VARCHAR(255) NOT NULL,
    provider_id     VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP,
    updated_at      TIMESTAMP,
    CONSTRAINT fk_user_social_accounts_user
        FOREIGN KEY (user_id) REFERENCES users (id)
);

